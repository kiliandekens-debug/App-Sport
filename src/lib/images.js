export function imageId(name, base) {
  if (!name) return null;
  const n = name.toLowerCase().trim();
  if (EXACT[n]) return EXACT[n];
  if (base && EXACT[base.toLowerCase().trim()]) return EXACT[base.toLowerCase().trim()];
  for (const [re, id] of RULES) if (re.test(n)) return id;
  return null;
}

export function imagesOf(name, base) {
  const id = imageId(name, base);
  return id ? [`${BASE}${id}/0.jpg`, `${BASE}${id}/1.jpg`] : [];
}
